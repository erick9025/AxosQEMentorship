console.log("****FOR****");
for(let caseNumFc:number=1; caseNumFc<=5; caseNumFc++) {
    console.log('Executing TC#'+caseNumFc);
}

console.log("****WHILE****");
let caseNumWc:number=1;
while(caseNumWc<=5) {
    console.log('Executing TC#'+caseNumWc);
    caseNumWc++;
}

console.log("****DO-WHILE****");
let caseNumDc:number=1;
do{
    console.log('Executing TC#'+caseNumDc);
    caseNumDc++;
}while (caseNumDc<=5);